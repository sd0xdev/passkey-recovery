#!/usr/bin/env node
// License check and notice generation for every npm package this project ships.
// The shipped set is the lockfile's production packages (the runner installs them) plus the packages Vite bundles into the
// UI from devDependencies (React, the fonts). Every other dev package is checked against a wider allowlist.
//   node scripts/release/licenses.mjs --check   fail on a disallowed license or a stale licenses/npm-shipped.txt
//   node scripts/release/licenses.mjs --write   regenerate licenses/npm-shipped.txt
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..', '..');
const OUT = join(root, 'licenses', 'npm-shipped.txt');
// Bundled into dist/ by Vite although they are devDependencies (the runner does not install them).
const BUNDLED_DEV = ['react', 'react-dom', 'scheduler', '@fontsource/atkinson-hyperlegible-next', '@fontsource/atkinson-hyperlegible-mono'];
const SHIPPED_OK = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '0BSD', 'MIT OR Apache-2.0', 'OFL-1.1']);
// Test, build and deploy tools only (never shipped). MPL-2.0: axe-core (tests) and lightningcss (build). LGPL-3.0-or-later:
// libvips inside sharp, which wrangler's local simulator (miniflare) installs; it never enters dist/ or the runner.
const DEV_OK = new Set([...SHIPPED_OK, 'MPL-2.0', 'BlueOak-1.0.0', 'CC0-1.0', 'Python-2.0', 'LGPL-3.0-or-later', 'Apache-2.0 AND LGPL-3.0-or-later', 'Apache-2.0 AND LGPL-3.0-or-later AND MIT']);

const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
const name = (path) => path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length);
const rows = [];
const problems = [];
for (const [path, meta] of Object.entries(lock.packages)) {
  if (!path) continue;
  const pkg = name(path);
  const shipped = !meta.dev || BUNDLED_DEV.includes(pkg);
  // TypeScript is a peer of abitype, so the lockfile marks it non-dev; nothing in dist/ or dist-server/ loads it at runtime.
  const runtime = shipped && !pkg.startsWith('@typescript/') && pkg !== 'typescript';
  const license = meta.license ?? 'UNKNOWN';
  const ok = (runtime ? SHIPPED_OK : DEV_OK).has(license);
  if (!ok) problems.push(`${pkg}@${meta.version}: license ${license} is not allowed for a ${runtime ? 'shipped' : 'dev-only'} package`);
  if (runtime) rows.push({ path, pkg, version: meta.version, license, optional: !!meta.optional });
}

function licenseText(path) {
  const dir = join(root, path);
  if (!existsSync(dir)) return null; // an optional package for another platform (e.g. a different Anvil binary)
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
  return file ? readFileSync(join(dir, file), 'utf8').trim() : null;
}

rows.sort((a, b) => (a.pkg + a.version).localeCompare(b.pkg + b.version));
const seen = new Set();
const parts = [
  'Licenses of the npm packages shipped by Passkey Recovery by sd0x',
  'Generated by scripts/release/licenses.mjs from package-lock.json. Do not edit by hand.',
  '',
];
for (const r of rows) {
  const key = `${r.pkg}@${r.version}`;
  if (seen.has(key)) continue;
  seen.add(key);
  const text = licenseText(r.path);
  parts.push('='.repeat(78), `${key} — ${r.license}${r.optional ? ' (optional, platform-specific)' : ''}`, '-'.repeat(78));
  if (text) parts.push(text);
  else if (r.optional) parts.push(`Not installed on the machine that generated this file; license per its package.json: ${r.license}. The package ships its own license file.`);
  else problems.push(`${key}: no LICENSE file found in ${r.path}`);
  parts.push('');
}
const generated = parts.join('\n');

const mode = process.argv[2];
if (mode === '--write') {
  writeFileSync(OUT, generated);
  console.log(`wrote ${OUT} (${seen.size} packages)`);
} else if (mode === '--check') {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  // Optional per-platform packages make the text machine-dependent; compare the package list, not the bytes.
  const list = (s) => s.split('\n').filter((l) => / — /.test(l) && /@/.test(l)).map((l) => l.split(' — ')[0]);
  if (JSON.stringify(list(current)) !== JSON.stringify(list(generated))) problems.push('licenses/npm-shipped.txt is stale: run node scripts/release/licenses.mjs --write');
} else {
  console.error('usage: licenses.mjs --check | --write');
  process.exit(2);
}
for (const p of problems) console.error(`license: ${p}`);
console.log(`license check: ${seen.size} shipped packages, ${problems.length} problem(s)`);
process.exit(problems.length ? 1 : 0);
