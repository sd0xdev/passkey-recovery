#!/usr/bin/env node
// Builds the public file set from an explicit allowlist (scripts/release/public-allowlist.json) — never "everything
// except" — into a fresh directory, writes MANIFEST.sha256 (one line per file) and prints its digest.
//   node scripts/release/export.mjs <out-dir> [--force]
// The output is what the public repository's first commit contains; scan it with scripts/release/scan.mjs.
// A few files are generated rather than copied (GENERATED below): the public .npmrc carries only the two npm
// settings the project pins, because a maintainer's local .npmrc is untracked and may hold registry or auth lines.
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';

const root = resolve(import.meta.dirname, '..', '..');
const [outArg, ...rest] = process.argv.slice(2);
if (!outArg) {
  console.error('usage: export.mjs <out-dir> [--force]');
  process.exit(2);
}
const out = resolve(outArg);
// Allowed: a folder outside the repository that does not contain it, or release-out/ (git-ignored) and below.
// Checked on path segments, so release-outside/ is not release-out/, and --force can never remove the repository.
const inside = (child, parent) => { const r = relative(parent, child); return r === '' || (r !== '..' && !r.startsWith('..' + sep) && !isAbsolute(r)); };
if (inside(root, out) || (inside(out, root) && !inside(out, join(root, 'release-out')))) {
  console.error('the export must go outside the repository and not contain it (or under release-out/, which is git-ignored)');
  process.exit(2);
}
if (existsSync(out)) {
  if (!rest.includes('--force')) {
    console.error(`${out} exists; pass --force to replace it`);
    process.exit(2);
  }
  rmSync(out, { recursive: true, force: true });
}
const { include, exclude } = JSON.parse(readFileSync(join(root, 'scripts/release/public-allowlist.json'), 'utf8'));
const deny = exclude.map((p) => new RegExp(p));
const files = [];
const missing = [];
const walk = (rel) => {
  const abs = join(root, rel);
  if (!existsSync(abs)) return missing.push(rel);
  if (deny.some((r) => r.test(rel) || r.test(`${rel}/`))) return;
  if (statSync(abs).isDirectory()) for (const e of readdirSync(abs).sort()) walk(`${rel}/${e}`);
  else files.push(rel);
};
for (const p of include) walk(p);
if (missing.length) {
  console.error(`allowlisted paths missing: ${missing.join(', ')}`);
  process.exit(1);
}
const GENERATED = { '.npmrc': 'engine-strict=true\nsave-exact=true\n' };
const generatedListed = files.filter((f) => f in GENERATED);
if (generatedListed.length) {
  console.error(`generated by the export, must not be allowlisted: ${generatedListed.join(', ')}`);
  process.exit(1);
}
const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');
const lines = [];
for (const f of files.sort()) {
  mkdirSync(dirname(join(out, f)), { recursive: true });
  cpSync(join(root, f), join(out, f), { preserveTimestamps: false });
  lines.push(`${sha256(readFileSync(join(root, f)))}  ${f}`);
}
for (const [f, body] of Object.entries(GENERATED)) {
  writeFileSync(join(out, f), body);
  lines.push(`${sha256(body)}  ${f}`);
}
lines.sort((a, b) => (a.slice(66) < b.slice(66) ? -1 : 1));
const manifest = `${lines.join('\n')}\n`;
writeFileSync(join(out, 'MANIFEST.sha256'), manifest);
const digest = sha256(manifest);
console.log(JSON.stringify({ out: relative(process.cwd(), out) || '.', files: lines.length, manifestSha256: digest }));
