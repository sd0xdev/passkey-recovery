/** A fresh context with NO injected wallet; every request outside `allow` is blocked and recorded. */
async function openAt(browser: Browser, url: string, allow: RegExp): Promise<Page> {
  const ctx = await browser.newContext({ acceptDownloads: true });
  opened.push(ctx);
  const page = await ctx.newPage();
  page.on('request', (r) => sent.push({ url: r.url(), body: r.postData() ?? '' }));
  // The page's own blob: URLs (the keystore download) are same-origin, not a network request.
  await page.route((u) => !allow.test(u.href.replace(/^blob:/, '')), (route) => {
    external.push(route.request().url());
    return route.abort('blockedbyclient');
  });
  await page.goto(url);
  return page;
}

/**
 * axe in EN and 繁中. With a sheet open the top-bar language toggle is inert behind the modal, so the
 * sheet is closed, the language switched, and the sheet reopened through `reopen`.
 */
async function axeBoth(p: Page, label: string, sheet?: { id: string; reopen: () => Promise<void> }) {
  const toggle = async () => {
    if (sheet) await p.getByTestId(`${sheet.id}-close`).click();
    await p.getByTestId('lang-toggle').click();
    if (sheet) {
      await sheet.reopen();
      await expect(p.getByTestId(sheet.id)).toBeVisible();
    }
  };
  for (const lang of ['en', 'zh'] as const) {
    if (lang === 'zh') await toggle();
    const r = await new AxeBuilder({ page: p }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa']).analyze();
    expect(r.violations.map((v) => `${label}/${lang}: ${v.id} ${v.nodes[0]?.target.join(' ')} ${v.nodes[0]?.failureSummary ?? ''}`)).toEqual([]);
  }
  await toggle();
  await expect(p.locator('html')).toHaveAttribute('lang', 'en');
}

