/** Sends every deploy step through the configured gas payer until the move step opens. */
async function deployAll(page: Page) {
  // The step plans on entry; no plan click.
  await expect(page.getByTestId('deploy')).toHaveAttribute('data-progress', /^\d+\/\d+$/, { timeout: 120_000 });
  const moveOpen = page.locator('li[data-step="move"][data-state="current"]');
  const send = page.getByTestId('deploy-send');
  const next = async () => ((await moveOpen.count()) ? 'done' : (await send.count()) && (await send.isEnabled()) ? 'send' : 'wait');
  for (let i = 0; i < 12; i++) {
    await expect.poll(next, { timeout: 120_000 }).not.toBe('wait');
    if ((await next()) === 'done') break;
    const before = await page.getByTestId('deploy').getAttribute('data-progress');
    // The full payer address in the step preview and in the final confirmation (GAS-01), not only the chip.
    const payer = await payerOf(page);
    expect(payer).toMatch(/^0x[0-9a-fA-F]{40}$/);
    await expect(page.getByTestId('deploy-payer')).toHaveAttribute('data-value', sameAddress(payer));
    await send.click();
    await expect(page.getByTestId('deploy-confirm-payer')).toHaveAttribute('data-value', sameAddress(payer));
    await page.getByTestId('deploy-send-confirm').click();
    await expect(page.getByTestId('deploy-refused')).toHaveCount(0);
    await expect.poll(async () => (await moveOpen.count()) || (await page.getByTestId('deploy').getAttribute('data-progress')) !== before, { timeout: 120_000 }).toBeTruthy();
  }
  await expect(moveOpen).toHaveCount(1, { timeout: 120_000 });
}

/** Drafts, signs with the fixture Passkey and sends 1 USDT0; returns once Track shows the receipt. */
async function moveOne(page: Page, seed: number, o: { trackingWriteFailsOnce?: boolean; walletRejectsOnce?: MockWallet; relayAnswerLost?: boolean } = {}) {
  const payer = await payerOf(page);
  expect(payer).toMatch(/^0x[0-9a-fA-F]{40}$/);
  await page.getByTestId('move-asset').selectOption({ label: 'USDT0' });
  await page.getByTestId('move-amount').fill('1');
  await page.getByTestId('move-to').fill(world.recipient);
  await page.getByTestId('move-to-again').fill(world.recipient);
  await page.getByTestId('move-review').click();
  const sign = page.getByTestId('sign');
  await expect(sign).toBeVisible({ timeout: 120_000 });
  // The no-extension Passkey path is offered first: a request code for exactly this hash.
  const hash = (await sign.getAttribute('data-userop-hash')) as `0x${string}`;
  await expect(page.getByTestId('sign-bookmarklet-code')).toHaveText(/^cbpr1:userop:[A-Za-z0-9_-]{43}$/);
  const a = buildAssertion({ challenge: hexToBytes(hash), kind: 'userop', key: syntheticKey(seed) });
  await page.getByTestId('sign-assertion').fill(a.json);
  await page.getByTestId('sign-submit').click();
  await expect(page.getByTestId('signed')).toBeVisible({ timeout: 120_000 });
  await page.getByTestId('send').click();
  const sheet = page.getByTestId('send-sheet');
  // GAS-01: the irreversible sheet names the full gas payer — the File / 1Password key, not the source account.
  await expect(sheet.getByTestId('manifest-payer')).toHaveAttribute('data-value', sameAddress(payer));
  await expect(sheet.getByTestId('manifest-from')).not.toHaveAttribute('data-value', sameAddress(payer));
  await sheet.getByTestId('send-typed').fill('1');
  if (o.trackingWriteFailsOnce) {
    // Regression: the tracking record cannot be written, so nothing is sent — and the plan must come back
    // to signed for this payer (not stay stuck in sending), so the same signature can be sent once it works.
    await page.evaluate(() => {
      const orig = Storage.prototype.setItem;
      Storage.prototype.setItem = function (k: string, v: string) {
        if (k === 'cbpr.tracking.v1') {
          Storage.prototype.setItem = orig;
          throw new DOMException('synthetic quota', 'QuotaExceededError');
        }
        return orig.call(this, k, v);
      };
    });
    await sheet.getByTestId('send-confirm').click({ timeout: 15_000 });
    await expect(page.getByText('could not save the tracking record, so nothing was sent')).toBeVisible({ timeout: 30_000 });
    await expect(page.getByTestId('move-sent')).toHaveCount(0);
    await expect(page.getByTestId('signed')).toBeVisible({ timeout: 30_000 });
    await page.getByTestId('send').click();
    await expect(sheet.getByTestId('manifest-payer')).toHaveAttribute('data-value', sameAddress(payer));
    await sheet.getByTestId('send-typed').fill('1');
  }
  if (o.walletRejectsOnce) {
    // UX-02 cancel: the user declines in the browser wallet → nothing was sent, no tracking row, and the same
    // signature can be sent again.
    const w = o.walletRejectsOnce;
    const sentBefore = w.sent.length;
    const rowsBefore = await page.getByTestId('track-row').count();
    // First the wallet keeps the request open: the record is kept before it is asked, so Track already polls
    // it and reads "unknown, no hash" — the send under way, never the "attention" cue (regression, J2 r7).
    const kinds = () => page.evaluate(() => (window as unknown as { __audio: AudioLog }).__audio.kinds);
    w.next('defer');
    await sheet.getByTestId('send-confirm').click({ timeout: 15_000 });
    await expect.poll(() => w.deferred(), { timeout: 60_000 }).toBe(1);
    await expect(page.getByTestId('track-row')).toHaveCount(rowsBefore + 1);
    await expect(page.getByTestId('track-row').first()).toHaveAttribute('data-state', 'unknown', { timeout: 60_000 });
    await page.waitForTimeout(3_500);
    expect(await kinds(), 'no attention cue while the wallet still has the request').not.toContain('triangle');
    w.answerDeferred('reject');
    await expect(page.getByText('You cancelled in your wallet. Nothing was sent.')).toBeVisible({ timeout: 60_000 });
    await expect(page.getByTestId('track-row')).toHaveCount(rowsBefore);
    expect(await kinds()).not.toContain('triangle');
    expect(w.sent.length).toBe(sentBefore);
    await expect(page.getByTestId('signed')).toBeVisible({ timeout: 30_000 });
    await page.getByTestId('send').click();
    await sheet.getByTestId('send-typed').fill('1');
    w.next('reject');
    await sheet.getByTestId('send-confirm').click({ timeout: 15_000 });
    await expect(page.getByText('You cancelled in your wallet. Nothing was sent.')).toBeVisible({ timeout: 60_000 });
    await expect(page.getByTestId('move-sent')).toHaveCount(0);
    expect(w.sent.length).toBe(sentBefore);
    await expect(page.getByTestId('track-row')).toHaveCount(rowsBefore);
    await expect(page.getByTestId('signed')).toBeVisible({ timeout: 30_000 });
    await page.getByTestId('send').click();
    await sheet.getByTestId('send-typed').fill('1');
  }
  if (o.relayAnswerLost) {
    // The runner relays for real, but its answer never reaches the page: whether it left is unknown, so Move
    // shows it as unknown (Track keeps it) and never offers Send again.
    await page.route('**/api/transfer/relay', async (r) => {
      await r.fetch();
      await r.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'runner unavailable' }) });
    });
  }
  await sheet.getByTestId('send-confirm').click({ timeout: 15_000 });
  await expect(page.getByTestId('move-sent')).toBeVisible({ timeout: 60_000 });
  if (o.relayAnswerLost) {
    await expect(page.getByTestId('move')).toHaveAttribute('data-plan-state', 'unknown');
    await expect(page.getByTestId('app-error')).toContainText('do not send it again');
    await expect(page.getByTestId('send')).toHaveCount(0);
    await expect(page.getByTestId('move-clear-signed')).toHaveCount(0);
    await page.unroute('**/api/transfer/relay');
  }
  const row = page.getByTestId('track-row').first();
  await expect(row).toHaveAttribute('data-state', /confirmed|final/, { timeout: 60_000 });
  await expect(row.getByTestId('receipt')).toContainText('1 USDT0');
}

