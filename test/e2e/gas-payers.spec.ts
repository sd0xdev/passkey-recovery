/**
 * Send on the signed plan with the runner's send-request answer held back; while it is held the earlier record
 * stops reading (the hold); then the answer is let through. The native path gives up before the signer is asked and
 * tells the runner nothing was sent — `report` shapes that call's transport. Returns a count of relays since.
 */
async function nativeSendHeld(page: Page, report: (r: Route) => Promise<void>) {
  const sheet = page.getByTestId('send-sheet');
  await page.getByTestId('send').click();
  await sheet.getByTestId('send-typed').fill('0.01');
  let releaseIssue!: () => void;
  const issued = new Promise<void>((r) => (releaseIssue = r));
  let runnerIssued!: () => void;
  const issuedByRunner = new Promise<void>((r) => (runnerIssued = r));
  await page.route(`${E2E_RUNNER}/api/transfer/send-request`, async (r) => {
    const answer = await r.fetch();
    runnerIssued();
    await issued;
    return r.fulfill({ response: answer });
  });
  await page.route(`${E2E_RUNNER}/api/transfer/signer-aborted`, report);
  const relaysBefore = sent.filter((q) => q.url.endsWith('/api/transfer/relay')).length;
  await sheet.getByTestId('send-confirm').click({ timeout: 15_000 });
  await issuedByRunner;
  await page.route(`${E2E_RUNNER}/api/track`, trackerDown);
  await expect(page.getByTestId('move-gate-held')).toBeVisible({ timeout: 30_000 });
  releaseIssue();
  await page.unroute(`${E2E_RUNNER}/api/transfer/send-request`);
  return { relays: () => sent.filter((q) => q.url.endsWith('/api/transfer/relay')).length - relaysBefore };
}

